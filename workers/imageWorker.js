const amqp = require("amqplib");
const sharp = require("sharp");
const path = require("path");
const fs = require("fs/promises");
const mongoose = require("mongoose");
const Dish = require("../models/dish");

const QUEUE = "image_processing";
const foodsDir = path.join(__dirname, "..", "public", "images", "foods");
const uploadsDir = path.join(foodsDir, "uploads");
const processedDir = path.join(foodsDir, "processed");

async function connectWithRetry() {
    while (true) {
        try {
            return await amqp.connect(process.env.RABBITMQ_URL);
        } catch (error) {
            console.error("RabbitMQ not ready; retrying in 3 seconds:", error.message);
            await new Promise((resolve) => setTimeout(resolve, 3000));
        }
    }
}

async function processTask(task) {
    const { dishId, filename } = task;

    // Only accept a plain filename generated by the upload route.
    if (!dishId || typeof filename !== "string" || path.basename(filename) !== filename) {
        throw new Error("Invalid image task payload");
    }

    const sourcePath = path.join(uploadsDir, filename);
    const outputFilename = `${path.parse(filename).name}.webp`;
    const outputPath = path.join(processedDir, outputFilename);
    const publicImagePath = `/images/foods/processed/${outputFilename}`;

    await fs.mkdir(processedDir, { recursive: true });

    await sharp(sourcePath)
        .rotate()
        .resize({
            width: 1200,
            height: 1200,
            fit: "inside",
            withoutEnlargement: true
        })
        .webp({ quality: 80 })
        .toFile(outputPath);

    const updated = await Dish.findByIdAndUpdate(
        dishId,
        { image: publicImagePath, imageStatus: "completed", imageError: null },
        { returnDocument: "after" }
    );

    if (!updated) {
        await fs.unlink(outputPath).catch(() => {});
        throw new Error(`Dish ${dishId} no longer exists`);
    }

    // Remove the original only after the database points to the processed image.
    await fs.unlink(sourcePath).catch((error) => {
        console.warn("Could not remove original upload:", error.message);
    });

    console.log(`Processed image for dish ${dishId}: ${publicImagePath}`);
}

async function main() {
    await mongoose.connect(process.env.MONGODB_URI);
    const connection = await connectWithRetry();
    const channel = await connection.createChannel();

    await channel.assertQueue(QUEUE, { durable: true });
    channel.prefetch(1);

    console.log("Image Worker is waiting for tasks...");

    channel.consume(QUEUE, async (message) => {
        if (!message) return;

        let task;
        try {
            task = JSON.parse(message.content.toString());
            await processTask(task);
            channel.ack(message);
        } catch (error) {
            console.error("Image task failed:", error.message);

            // This basic version records failure and acknowledges the task.
            // For production, use bounded retries and a dead-letter queue.
            if (task?.dishId) {
                await Dish.findByIdAndUpdate(task.dishId, {
                    imageStatus: "failed",
                    imageError: "Image processing failed"
                }).catch((dbError) => console.error("Could not update dish status:", dbError.message));
            }
            channel.ack(message);
        }
    });
}

main().catch((error) => {
    console.error("Image Worker failed to start:", error);
    process.exit(1);
});
